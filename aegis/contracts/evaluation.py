"""
AEGIS-NET Universal Data Contracts: Evaluation, Safety & Reporting
Defines the schemas produced by Padmini's validation layer:
- Conflict detection & Cross-agent debate
- Doctor-Critic verification & hallucination checks
- Red/Yellow/Green Triage classification
- Structured clinical report & FHIR output
"""

from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from aegis.contracts.findings import ClinicalFinding


class TriageLevel(str, Enum):
    GREEN = "GREEN"    # Routine / Low Acuity - Safe for standard queue
    YELLOW = "YELLOW"  # Urgent / Moderate Risk - Timely evaluation needed
    RED = "RED"        # Emergent / Critical - Immediate resuscitation or ICU consult


class ConflictItem(BaseModel):
    """Represents a discrepancy between modalities detected during cross-agent evaluation."""
    conflict_id: str
    modalities_involved: List[str]
    description: str
    severity: str = "moderate"
    recommended_resolution: Optional[str] = None


class DoctorCriticVerdict(BaseModel):
    """Output of Padmini's Doctor-Critic verification layer."""
    is_plausible: bool = Field(..., description="Whether the combined findings make clinical sense")
    hallucination_detected: bool = Field(default=False, description="Whether ungrounded claims were found")
    guideline_concordant: bool = Field(default=True, description="Whether assessment aligns with clinical guidelines")
    verification_confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence of the critic")
    critique_notes: str = Field(..., description="Doctor-critic feedback for the encounter")
    needs_retry: bool = Field(default=False, description="Whether orchestrator must trigger a cyclic re-evaluation")
    retry_guidance: Optional[str] = Field(None, description="Actionable prompt to guide agent re-focusing on retry")


class FinalClinicalReport(BaseModel):
    """The structured final report generated by Padmini's reporting layer."""
    patient_id: str
    encounter_id: str
    triage: TriageLevel
    synthesized_diagnosis: List[str]
    critical_findings: List[ClinicalFinding]
    recommended_actions: List[str]
    critic_verdict: DoctorCriticVerdict
    fhir_bundle: Dict[str, Any] = Field(default_factory=dict)
    audit_trace_id: str
